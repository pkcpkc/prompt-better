import Foundation
import CoreGraphics
import ImageIO
import SwiftUI

// MARK: - Persisted model

/// One persisted chat. The model is chosen when the chat is created and never changes afterwards.
struct Conversation: Identifiable, Codable, Equatable {
    let id: UUID
    let modelId: String
    var title: String
    let createdAt: Date
    var updatedAt: Date
    var messages: [ChatMessage]
}

struct ChatMessage: Identifiable, Codable, Equatable {
    struct Attachment: Identifiable, Codable, Equatable {
        let id: UUID
        let name: String
        let kind: ChatAttachment.Kind
        /// The text the model received in place of this media (OCR, transcription, PDF text).
        /// `nil` when the media was passed to the model as-is.
        var extractedText: String?
        var hasThumbnail: Bool
    }

    let id: UUID
    let isUser: Bool
    var text: String
    var attachments: [Attachment] = []
    /// User prompt with attachment content extracted to text; reused as history on later turns.
    var promptText: String?
    var isError = false
    /// Ids of images the model generated for this (assistant) message; files live next to the attachments.
    var generatedImages: [UUID]?
}

// MARK: - Store

/// Owns all chats and their on-disk data. Layout, one folder per chat so deleting it removes everything:
///
///     Application Support/AIBridgeChats/<conversation id>/
///         conversation.json            messages and metadata
///         attachments/<id>.parts.json  the original media (OpenAI content parts)
///         attachments/<id>.thumb.jpg   preview shown in the transcript
///         attachments/<id>.png         images generated by an image model
///
/// Turns run here rather than in a view, so a reply still lands in its chat when the user switches away.
@MainActor
final class ChatStore: ObservableObject {
    @Published private(set) var conversations: [Conversation] = []
    @Published private(set) var sending: Set<UUID> = []

    private let root: URL

    init(root: URL? = nil) {
        self.root = root ?? FileManager.default
            .urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("AIBridgeChats", isDirectory: true)
        load()
    }

    func conversation(_ id: UUID) -> Conversation? {
        conversations.first { $0.id == id }
    }

    func isSending(_ id: UUID) -> Bool { sending.contains(id) }

    // MARK: Create / delete

    @discardableResult
    func create(modelId: String) -> Conversation {
        let now = Date()
        let conversation = Conversation(id: UUID(), modelId: modelId, title: "New Chat", createdAt: now, updatedAt: now, messages: [])
        conversations.insert(conversation, at: 0)
        save(conversation)
        return conversation
    }

    /// Removes the chat, its messages and every stored attachment.
    func delete(_ id: UUID) {
        conversations.removeAll { $0.id == id }
        try? FileManager.default.removeItem(at: folder(for: id))
    }

    // MARK: Sending

    /// Appends the user's message, runs the turn and appends the reply. Safe against the chat being deleted meanwhile.
    func send(
        to id: UUID,
        text: String,
        attachments: [ChatAttachment],
        log: @escaping @MainActor (String) -> Void,
        ensureServer: @escaping @MainActor () async -> Void
    ) {
        guard let conversation = conversation(id), !sending.contains(id) else { return }
        let history = conversation.messages.filter { !$0.isError }
        let model = conversation.modelId

        let userMessage = ChatMessage(
            id: UUID(),
            isUser: true,
            text: text,
            attachments: attachments.map {
                .init(id: $0.id, name: $0.name, kind: $0.kind, extractedText: nil, hasThumbnail: $0.thumbnail != nil)
            }
        )
        update(id) { c in
            c.messages.append(userMessage)
            if c.title == "New Chat" { c.title = Self.title(text: text, attachments: attachments) }
        }
        sending.insert(id)

        Task {
            // Media first, so it survives even when the turn fails.
            for attachment in attachments { await writeAttachment(attachment, conversation: id) }

            await ensureServer()
            let note = attachments.isEmpty ? "" : ", \(attachments.count) attachment(s)"
            log("POST /v1/chat/completions (Chat Window: \(model)\(note))")

            let reply: ChatMessage
            do {
                if ChatModels.isImageModel(model) {
                    let png = try await ChatTurnRunner.generateImage(model: model, prompt: text)
                    let imageId = UUID()
                    await writeGeneratedImage(png, id: imageId, conversation: id)
                    log("200 POST /v1/images/generations (Chat Window: \(model))")
                    var message = ChatMessage(id: UUID(), isUser: false, text: "")
                    message.generatedImages = [imageId]
                    update(id) { $0.messages.append(message) }
                    sending.remove(id)
                    return
                }
                let outcome = try await ChatTurnRunner.run(model: model, history: history, text: text, attachments: attachments)
                log("200 POST /v1/chat/completions (Chat Window: \(model))")
                update(id) { c in
                    guard let index = c.messages.firstIndex(where: { $0.id == userMessage.id }) else { return }
                    c.messages[index].promptText = outcome.extractedPrompt
                    for i in c.messages[index].attachments.indices {
                        let attachmentId = c.messages[index].attachments[i].id
                        c.messages[index].attachments[i].extractedText = outcome.extractedText[attachmentId]
                    }
                }
                reply = ChatMessage(id: UUID(), isUser: false, text: outcome.reply)
            } catch {
                log("500 POST /v1/chat/completions (Chat Window: \(model)) - Error: \(error.localizedDescription)")
                reply = ChatMessage(id: UUID(), isUser: false, text: "Error: \(error.localizedDescription)", isError: true)
            }
            update(id) { $0.messages.append(reply) }
            sending.remove(id)
        }
    }

    private static func title(text: String, attachments: [ChatAttachment]) -> String {
        let source = text.isEmpty ? (attachments.first?.name ?? "New Chat") : text
        let line = source.split(whereSeparator: \.isNewline).first.map(String.init) ?? source
        return line.count > 40 ? String(line.prefix(40)) + "…" : line
    }

    // MARK: Attachments

    func thumbnail(conversation id: UUID, attachment: UUID) async -> CGImage? {
        let url = attachmentsFolder(for: id).appendingPathComponent("\(attachment).thumb.jpg")
        return await Task.detached {
            guard let data = try? Data(contentsOf: url),
                  let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
            return CGImageSourceCreateImageAtIndex(source, 0, nil)
        }.value
    }

    /// Full-size image generated by an image model.
    func generatedImage(conversation id: UUID, image: UUID) async -> CGImage? {
        let url = generatedImageURL(conversation: id, image: image)
        return await Task.detached {
            guard let data = try? Data(contentsOf: url),
                  let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
            return CGImageSourceCreateImageAtIndex(source, 0, nil)
        }.value
    }

    func generatedImageURL(conversation id: UUID, image: UUID) -> URL {
        attachmentsFolder(for: id).appendingPathComponent("\(image).png")
    }

    func attachmentPartsURL(conversation id: UUID, attachment: UUID) -> URL {
        attachmentsFolder(for: id).appendingPathComponent("\(attachment).parts.json")
    }

    private func writeGeneratedImage(_ png: Data, id imageId: UUID, conversation id: UUID) async {
        let folder = attachmentsFolder(for: id)
        await Task.detached {
            try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try? png.write(to: folder.appendingPathComponent("\(imageId).png"), options: .atomic)
        }.value
    }

    private func writeAttachment(_ attachment: ChatAttachment, conversation id: UUID) async {
        let folder = attachmentsFolder(for: id)
        let parts = attachment.parts
        let thumb = attachment.thumbnail.flatMap(ChatAttachmentLoader.jpegData(from:))
        let attachmentId = attachment.id
        await Task.detached {
            let fm = FileManager.default
            try? fm.createDirectory(at: folder, withIntermediateDirectories: true)
            if let data = try? JSONEncoder().encode(parts) {
                try? data.write(to: folder.appendingPathComponent("\(attachmentId).parts.json"), options: .atomic)
            }
            if let thumb {
                try? thumb.write(to: folder.appendingPathComponent("\(attachmentId).thumb.jpg"), options: .atomic)
            }
        }.value
    }

    // MARK: Disk

    private func folder(for id: UUID) -> URL { root.appendingPathComponent(id.uuidString, isDirectory: true) }
    private func attachmentsFolder(for id: UUID) -> URL { folder(for: id).appendingPathComponent("attachments", isDirectory: true) }

    /// Applies a change; drops it silently if the chat was deleted in the meantime.
    private func update(_ id: UUID, _ change: (inout Conversation) -> Void) {
        guard let index = conversations.firstIndex(where: { $0.id == id }) else { return }
        change(&conversations[index])
        conversations[index].updatedAt = Date()
        save(conversations[index])
        conversations.sort { $0.updatedAt > $1.updatedAt }
    }

    private func save(_ conversation: Conversation) {
        let folder = folder(for: conversation.id)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        if let data = try? encoder.encode(conversation) {
            try? data.write(to: folder.appendingPathComponent("conversation.json"), options: .atomic)
        }
    }

    private func load() {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        let folders = (try? FileManager.default.contentsOfDirectory(at: root, includingPropertiesForKeys: nil)) ?? []
        conversations = folders
            .compactMap { try? Data(contentsOf: $0.appendingPathComponent("conversation.json")) }
            .compactMap { try? decoder.decode(Conversation.self, from: $0) }
            .sorted { $0.updatedAt > $1.updatedAt }
    }
}
